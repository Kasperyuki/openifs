MODULE MO_OIFS_OROCIRRUS

USE PARKIND1, ONLY: JPIM, JPRB
USE YOMCST, ONLY: RCPD, RD, RG, RPI, RV
USE YOEGWD, ONLY: TEGWD
USE YOEPHLI, ONLY: TEPHLI

IMPLICIT NONE

PRIVATE
PUBLIC :: OIFS_OROCIRRUS_UPDRAFT

CONTAINS

SUBROUTINE OIFS_OROCIRRUS_UPDRAFT( &
  & YDEPHLI, YDEGWD, KIDIA, KFDIA, KLON, KLEV, &
  & PAPHM1, PAPM1, PGEOM1, PTM1, PQM1, PUM1, PVM1, &
  & PHSTD, PGAMMA, PTHETA, PSIG, PRHO_RCP, PVERVEL, PVERVX)

TYPE(TEPHLI), INTENT(IN) :: YDEPHLI
TYPE(TEGWD), INTENT(IN) :: YDEGWD
INTEGER(KIND=JPIM), INTENT(IN) :: KIDIA, KFDIA, KLON, KLEV
REAL(KIND=JPRB), INTENT(IN) :: PAPHM1(KLON,0:KLEV), PAPM1(KLON,KLEV)
REAL(KIND=JPRB), INTENT(IN) :: PGEOM1(KLON,KLEV), PTM1(KLON,KLEV), PQM1(KLON,KLEV)
REAL(KIND=JPRB), INTENT(IN) :: PUM1(KLON,KLEV), PVM1(KLON,KLEV)
REAL(KIND=JPRB), INTENT(IN) :: PHSTD(KLON), PGAMMA(KLON), PTHETA(KLON), PSIG(KLON)
REAL(KIND=JPRB), INTENT(IN) :: PRHO_RCP(KLON,KLEV), PVERVEL(KLON,KLEV)
REAL(KIND=JPRB), INTENT(INOUT) :: PVERVX(KLON,KLEV)

TYPE(TEPHLI) :: ZDEPHLI
TYPE(TEGWD) :: ZDEGWD
LOGICAL :: LLGWD(KLON)
INTEGER(KIND=JPIM) :: ICRIT(KLON), IKCRITH(KLON), IKENVH(KLON)
INTEGER(KIND=JPIM) :: IKNU(KLON), IKNU2(KLON)
INTEGER(KIND=JPIM) :: JK, JL
REAL(KIND=JPRB) :: ZTAU(KLON,KLEV+1), ZSTAB(KLON,KLEV+1)
REAL(KIND=JPRB) :: ZVPH(KLON,KLEV+1), ZRHO(KLON,KLEV+1)
REAL(KIND=JPRB) :: ZRI(KLON,KLEV+1), ZPSI(KLON,KLEV+1), ZZDEP(KLON,KLEV)
REAL(KIND=JPRB) :: ZULOW(KLON), ZVLOW(KLON), ZNU(KLON)
REAL(KIND=JPRB) :: ZD1(KLON), ZD2(KLON), ZDMOD(KLON), ZGAMMA(KLON)
REAL(KIND=JPRB) :: ZAMPL(KLON,KLEV), ZWAVE(KLON,KLEV), ZWNNUCL(KLON,KLEV)
REAL(KIND=JPRB) :: ZPLZ(KLON)
REAL(KIND=JPRB) :: ZBLOCK, ZDEPB, ZEFF, ZKDRAG, ZORO, ZNORM
REAL(KIND=JPRB) :: ZWIND, ZVT1, ZVT2, ZVPF
REAL(KIND=JPRB) :: ZLAMBDA, ZI, ZTEMPGW, ZWSIN, ZICE
REAL(KIND=JPRB) :: ZRHI, ZRHIVAL, ZSCR, ZSCR0
REAL(KIND=JPRB), PARAMETER :: ZSTEP_LONG = 1000._JPRB
REAL(KIND=JPRB), PARAMETER :: ZEPS = 1.E-12_JPRB

#include "gwsetup.intfb.h"
#include "gwprofil.intfb.h"

ZDEPHLI = YDEPHLI
ZDEGWD = YDEGWD
ZGAMMA(KIDIA:KFDIA) = PGAMMA(KIDIA:KFDIA)
LLGWD(KIDIA:KFDIA) = (PHSTD(KIDIA:KFDIA) > 50._JPRB) .AND. &
                      (PSIG(KIDIA:KFDIA) > ZEPS)

IF (.NOT.ANY(LLGWD(KIDIA:KFDIA))) RETURN

CALL GWSETUP(ZDEGWD,KIDIA,KFDIA,KLON,KLEV,LLGWD, &
  & IKCRITH,ICRIT,IKENVH,IKNU,IKNU2,PAPHM1,PAPM1,PUM1,PVM1,PTM1,PGEOM1,PHSTD, &
  & ZRHO,ZRI,ZSTAB,ZTAU,ZVPH,ZPSI,ZZDEP,ZULOW,ZVLOW,PTHETA,ZGAMMA,ZNU,ZD1,ZD2,ZDMOD)

IF (YDEPHLI%LPHYLIN) THEN
  ZKDRAG = YDEPHLI%RLPDRAG
ELSE
  ZKDRAG = YDEGWD%GKDRAG
END IF

DO JL=KIDIA,KFDIA
  IF (LLGWD(JL)) THEN
    ZBLOCK = PGEOM1(JL,IKENVH(JL))/RG
    ZEFF = 2._JPRB*MAX(0._JPRB,3._JPRB*PHSTD(JL)-ZBLOCK)
    ZTAU(JL,KLEV+1) = ZKDRAG*ZRHO(JL,KLEV+1)*PSIG(JL)*ZEFF**2 &
      & * ZVPH(JL,KLEV+1)*ZDMOD(JL)*SQRT(ZSTAB(JL,KLEV+1)) &
      & / (9._JPRB*MAX(PHSTD(JL),1._JPRB))
  END IF
END DO

CALL GWPROFIL(ZDEPHLI,ZDEGWD,KIDIA,KFDIA,KLON,KLEV,LLGWD, &
  & IKCRITH,ICRIT,IKENVH,IKNU,IKNU2,PAPHM1,ZRHO,ZSTAB,ZVPH,ZRI,ZTAU, &
  & ZDMOD,PSIG,PHSTD)

ZAMPL(KIDIA:KFDIA,:) = 0._JPRB
ZWAVE(KIDIA:KFDIA,:) = 0._JPRB
ZWNNUCL(KIDIA:KFDIA,:) = 0._JPRB
ZPLZ(KIDIA:KFDIA) = 0._JPRB

DO JL=KIDIA,KFDIA
  IF (LLGWD(JL)) THEN
    ZDEPB = 1._JPRB
    IF (IKENVH(JL) < KLEV) ZDEPB = MIN(SQRT(MAX(ZZDEP(JL,IKENVH(JL)),0._JPRB)),1._JPRB)
    ZPLZ(JL) = 2._JPRB*MAX( &
      & ABS(PHSTD(JL)/MAX(PSIG(JL),ZEPS)*COS(ZPSI(JL,KLEV+1))), &
      & ABS(PHSTD(JL)/(MAX(ZGAMMA(JL),ZEPS)*MAX(PSIG(JL),ZEPS)) &
      & * SIN(ZPSI(JL,KLEV+1))))*ZDEPB
  END IF
END DO

DO JK=1,KLEV
  DO JL=KIDIA,KFDIA
    IF (LLGWD(JL)) THEN
      ZORO = PSIG(JL)*ZDMOD(JL)/(4._JPRB*MAX(PHSTD(JL),1._JPRB))
      ZNORM = ZKDRAG*ZRHO(JL,JK)*SQRT(MAX(ZSTAB(JL,JK),ZDEGWD%GSSEC)) &
        & * MAX(ZVPH(JL,JK),ZDEGWD%GVSEC)*MAX(ZORO,ZEPS)
      ZAMPL(JL,JK) = MAX(0._JPRB,ZTAU(JL,JK+1)/MAX(ZNORM,ZDEGWD%GSSEC))
      ZWIND = MAX(SQRT(ZULOW(JL)**2+ZVLOW(JL)**2),ZDEGWD%GVSEC)
      ZVT1 = ZULOW(JL)*PUM1(JL,JK)+ZVLOW(JL)*PVM1(JL,JK)
      ZVT2 =-ZVLOW(JL)*PUM1(JL,JK)+ZULOW(JL)*PVM1(JL,JK)
      ZVPF = (ZVT1*ZD1(JL)+ZVT2*ZD2(JL))/(ZWIND*MAX(ZDMOD(JL),ZDEGWD%GTSEC))
      IF (ZPLZ(JL) > ZEPS) THEN
        ZWAVE(JL,JK) = RPI/ZPLZ(JL)*SQRT(ZAMPL(JL,JK))*MAX(0._JPRB,ZVPF)
      END IF
    END IF
  END DO
END DO

DO JK=1,KLEV
  ZICE = 0._JPRB
  DO JL=KIDIA,KFDIA
    IF (LLGWD(JL) .AND. ZPLZ(JL) >= 100._JPRB) THEN
      ZLAMBDA = 2._JPRB*ZPLZ(JL)
      ZSCR0 = (2.583_JPRB-PTM1(JL,JK)/207.83_JPRB)*100._JPRB
      ZICE = EXP(9.550426_JPRB-5723.265_JPRB/PTM1(JL,JK) &
        & +3.53068_JPRB*LOG(PTM1(JL,JK))-0.00728332_JPRB*PTM1(JL,JK))
      ZRHI = 100._JPRB*PAPM1(JL,JK)*PQM1(JL,JK)/((RD/RV)*ZICE)
      ZRHIVAL = ZRHI
      ZI = 1._JPRB
      DO WHILE (ZRHIVAL <= ZSCR0 .AND. ZI < ZLAMBDA)
        ZTEMPGW = MAX(100._JPRB,PTM1(JL,JK) &
          & - RG*RCPD*SQRT(ZAMPL(JL,JK)) &
          & * (SIN(1.5_JPRB*RPI+2._JPRB*RPI*ZI/ZLAMBDA)+1._JPRB))
        ZWSIN = ZWAVE(JL,JK)*SIN(2._JPRB*RPI*ZI/ZLAMBDA)
        ZICE = EXP(9.550426_JPRB-5723.265_JPRB/ZTEMPGW &
          & +3.53068_JPRB*LOG(ZTEMPGW)-0.00728332_JPRB*ZTEMPGW)
        ZRHIVAL = 100._JPRB*PAPM1(JL,JK)*PQM1(JL,JK)/((RD/RV)*ZICE)
        ZSCR = (2.418_JPRB-ZTEMPGW/245.68_JPRB)*100._JPRB
        ZSCR0 = ZSCR
        ZWNNUCL(JL,JK) = ZWSIN
        ZI = ZI+ZSTEP_LONG
      END DO
      ZWNNUCL(JL,JK) = MAX(0.001_JPRB,ZWNNUCL(JL,JK))
      PVERVX(JL,JK) = -100._JPRB*PVERVEL(JL,JK)*PRHO_RCP(JL,JK)/RG &
        & + 100._JPRB*ZWNNUCL(JL,JK)
    END IF
  END DO
END DO

END SUBROUTINE OIFS_OROCIRRUS_UPDRAFT

END MODULE MO_OIFS_OROCIRRUS
