SUBROUTINE ICE_INTERFACE( &
  & KIDIA, KFDIA, KLON, KTDIA, KLEV, LICENUCL, KNIC_CIRRUS, &
  & PAP, PIP, PLP, PTP, PTP0, PQP0, PRS1, PRSF1, PVERVEL, PCIRRUS_W, &
  & ZRHO, ZAP, ZTKEM1, ZXTM1, ZXTTE, ZM6RP, &
  & ZNACT, PGFL_YICNC, PGFL_YRE_ICE, &
  & LICECLD, PSNOWACL, PICEPROC, PRNICE, ZICNC, ZCDNCACT)

USE PARKIND1, ONLY: JPIM, JPRB
USE YOMHOOK, ONLY: LHOOK, DR_HOOK, JPHOOK
USE YOMCST, ONLY: RG, RPI
USE MO_ACTIV, ONLY: nfrzmod
USE MO_HAM, ONLY: nclass
USE TM5M7_DATA, ONLY: NMOD
USE MO_HAM_FREEZING, ONLY: ham_IN_setup
USE MO_CLOUD_MICRO_2M, ONLY: freezing_below_238K, het_mxphase_freezing, minimum_CDNC
USE MO_CIRRUS, ONLY: XFRZMSTR
USE MO_TIME_CONTROL, ONLY: time_step_len
USE MO_TRACDEF, ONLY: ntrac

IMPLICIT NONE

INTEGER(KIND=JPIM), INTENT(IN) :: KIDIA, KFDIA, KLON, KTDIA, KLEV
INTEGER(KIND=JPIM), INTENT(IN) :: KNIC_CIRRUS
LOGICAL, INTENT(IN) :: LICENUCL
REAL(KIND=JPRB), INTENT(IN) :: PAP(KLON,KLEV), PIP(KLON,KLEV), PLP(KLON,KLEV)
REAL(KIND=JPRB), INTENT(IN) :: PTP(KLON,KLEV), PTP0(KLON,KLEV), PQP0(KLON,KLEV)
REAL(KIND=JPRB), INTENT(IN) :: PRS1(KLON,0:KLEV)
REAL(KIND=JPRB), INTENT(IN) :: PRSF1(KLON,KLEV), PVERVEL(KLON,KLEV)
REAL(KIND=JPRB), INTENT(IN) :: PCIRRUS_W(KLON,KLEV) ! cirrus nucleation updraft [cm/s]
REAL(KIND=JPRB), INTENT(IN) :: ZRHO(KLON,KLEV), ZAP(KLON,KLEV), ZTKEM1(KLON,KLEV)
REAL(KIND=JPRB), INTENT(IN) :: ZXTM1(KLON,KLEV,ntrac), ZXTTE(KLON,KLEV,ntrac)
REAL(KIND=JPRB), INTENT(IN) :: ZM6RP(KLON,KLEV,NMOD)
REAL(KIND=JPRB), INTENT(IN) :: ZNACT(KLON,KLEV,nclass)
REAL(KIND=JPRB), INTENT(IN) :: PGFL_YICNC(KLON,KLEV), PGFL_YRE_ICE(KLON,KLEV)
LOGICAL, INTENT(IN) :: LICECLD(KLON,KLEV)
REAL(KIND=JPRB), INTENT(IN) :: PSNOWACL(KLON,KLEV), PICEPROC(KLON,KLEV,5)
REAL(KIND=JPRB), INTENT(IN) :: PRNICE
REAL(KIND=JPRB), INTENT(INOUT) :: ZICNC(KLON,KLEV), ZCDNCACT(KLON,KLEV)

INTEGER(KIND=JPIM), PARAMETER :: ZKROW = 1
INTEGER(KIND=JPIM), PARAMETER :: JPICE_FALL=1, JPICE_AGG=2, JPICE_MELT=3, JPICE_DETR=4, JPICE_SEC=5
REAL(KIND=JPRB), PARAMETER :: RHOICE = 925._JPRB
REAL(KIND=JPRB), PARAMETER :: ZEPSEC = 1.E-14_JPRB
REAL(KIND=JPRB), PARAMETER :: ZMIN_ICNC = 10._JPRB
REAL(KIND=JPRB), PARAMETER :: ZCONV_EFFR2MVR = 0.9_JPRB
REAL(KIND=JPRB), PARAMETER :: ZDETR_FACT_PK = 8.253E-3_JPRB
REAL(KIND=JPRB), PARAMETER :: ZDETR_POW_PK = 2.475_JPRB
REAL(KIND=JPRB), PARAMETER :: ZSEC_ICE_MASS = 1.E-12_JPRB

INTEGER(KIND=JPIM) :: JK
REAL(KIND=JPRB) :: ZNACT_STRAT(KLON,KLEV,nclass), ZNACT_CONV(KLON,KLEV,nclass)
REAL(KIND=JPRB) :: ZRWETKI(KLON,KLEV), ZRWETAI(KLON,KLEV), ZRWETCI(KLON,KLEV)
REAL(KIND=JPRB) :: ZFRACDUSOL(KLON,KLEV), ZFRACDUAI(KLON,KLEV), ZFRACDUCI(KLON,KLEV)
REAL(KIND=JPRB) :: ZFRACBCSOL(KLON,KLEV), ZFRACBCINSOL(KLON,KLEV), ZASCS(KLON,KLEV)
REAL(KIND=JPRB) :: ZAPNX(KLON,KLEV,NFRZMOD), ZAPRX(KLON,KLEV,NFRZMOD)
REAL(KIND=JPRB) :: ZAPSIGX(KLON,KLEV,NFRZMOD)
REAL(KIND=JPRB) :: ZAPNX_AVAILABLE(KLON,KLEV,NFRZMOD)
REAL(KIND=JPRB) :: TEMPIWC(KLON,KLEV), TEMPLWC(KLON,KLEV), ZCDNC_MIN(KLON,KLEV)
REAL(KIND=JPRB) :: ZESI(KLON,KLEV), SICE(KLON,KLEV), PRV_ICE(KLON,KLEV)
REAL(KIND=JPRB) :: ZRHO_RCP(KLON,KLEV), ZNINUCL(KLON,KLEV)
REAL(KIND=JPRB) :: ZVERVX(KLON,KLEV), ZRI(KLON,KLEV), ZNICEX(KLON,KLEV)
REAL(KIND=JPRB) :: ZQFRE(KLON,KLEV), ZFREZ(KLON,KLEV), ZFRLN(KLON,KLEV)
REAL(KIND=JPRB) :: ZTMP1_2D(KLON,KLEV), ZTMP2_2D(KLON,KLEV), ZTMP3_2D(KLON,KLEV)
REAL(KIND=JPRB) :: ZDPG(KLON), ZNUMFLUX(KLON), ZNUMMR(KLON)
REAL(KIND=JPRB) :: ZICEBEFORE(KLON), ZLIQBEFORE(KLON)
REAL(KIND=JPRB) :: ZMELTFRAC(KLON), ZAGGFRAC(KLON), ZRIMEFRAC(KLON)
REAL(KIND=JPRB) :: ZMELTNUM(KLON), ZSELFLOSS(KLON), ZTOTALLOSS(KLON)
REAL(KIND=JPRB) :: ZDETR_REFF(KLON,KLEV), ZDETR_RVOL(KLON,KLEV), ZNIDETR(KLON,KLEV)
REAL(KIND=JPRB) :: ZNISEC(KLON,KLEV)
LOGICAL :: LD_HET, LL_CC(KLON,KLEV), LL1(KLON,KLEV), LL_ICE(KLON,KLEV)
LOGICAL :: LL4_2D(KLON,KLEV), LL_FRZ_BELOW_238K(KLON), LL_MXPHASE_FRZ(KLON)
REAL(KIND=JPHOOK) :: ZHOOK_HANDLE

IF (LHOOK) CALL DR_HOOK('ICE_INTERFACE',0,ZHOOK_HANDLE)

IF (LICENUCL) THEN
  ZNACT_STRAT(KIDIA:KFDIA,:,:) = ZNACT(KIDIA:KFDIA,:,:)
  ZNACT_CONV(KIDIA:KFDIA,:,:) = ZNACT(KIDIA:KFDIA,:,:)

  TEMPIWC(KIDIA:KFDIA,:) = MAX(PIP(KIDIA:KFDIA,:),0._JPRB)
  TEMPLWC(KIDIA:KFDIA,:) = MAX(PLP(KIDIA:KFDIA,:),0._JPRB) * ZRHO(KIDIA:KFDIA,:)
  DO JK=1,KLEV
    ZCDNC_MIN(KIDIA:KFDIA,JK) = minimum_CDNC(KLON,KFDIA,TEMPLWC(KIDIA:KFDIA,JK))
  END DO

  ZICNC(KIDIA:KFDIA,:) = MAX(PGFL_YICNC(KIDIA:KFDIA,:) * 1.E6_JPRB,1.E-12_JPRB)
  LL_CC(KIDIA:KFDIA,:) = PAP(KIDIA:KFDIA,:) >= ZEPSEC
  LL1(KIDIA:KFDIA,:) = LL_CC(KIDIA:KFDIA,:) .AND. (PLP(KIDIA:KFDIA,:) > 1.E-12_JPRB)
  ZTMP1_2D(KIDIA:KFDIA,:) = MAX(ZCDNCACT(KIDIA:KFDIA,:),ZCDNC_MIN(KIDIA:KFDIA,:))
  ZCDNCACT(KIDIA:KFDIA,:) = MERGE(ZTMP1_2D(KIDIA:KFDIA,:),1.E-12_JPRB,LL1(KIDIA:KFDIA,:))

  ! Add the number carried by the convective ice mass detrained into CLOUDSC.
  ZTMP1_2D(KIDIA:KFDIA,:) = MIN(PTP0(KIDIA:KFDIA,:)-273.15_JPRB,0._JPRB)
  ZDETR_REFF(KIDIA:KFDIA,:) = MAX(23.2_JPRB*EXP(0.015_JPRB*ZTMP1_2D(KIDIA:KFDIA,:)),1._JPRB)
  ZDETR_RVOL(KIDIA:KFDIA,:) = MAX(1.E-6_JPRB, &
    & ZCONV_EFFR2MVR*1.E-6_JPRB*ZDETR_REFF(KIDIA:KFDIA,:))
  ZNIDETR(KIDIA:KFDIA,:) = ZCONV_EFFR2MVR*(0.5E-2_JPRB)**ZDETR_POW_PK &
    & * 1000._JPRB/ZDETR_FACT_PK*ZRHO(KIDIA:KFDIA,:) &
    & * MAX(PICEPROC(KIDIA:KFDIA,:,JPICE_DETR),0._JPRB) &
    & / (MAX(ZAP(KIDIA:KFDIA,:),0.01_JPRB)*ZDETR_RVOL(KIDIA:KFDIA,:)**ZDETR_POW_PK)
  ZICNC(KIDIA:KFDIA,:) = ZICNC(KIDIA:KFDIA,:) + MAX(ZNIDETR(KIDIA:KFDIA,:),0._JPRB)

  ! Transfer ice number to droplet number in proportion to OIFS ice melting.
  DO JK=1,KLEV
    ZICEBEFORE(KIDIA:KFDIA) = MAX(PIP(KIDIA:KFDIA,JK),0._JPRB) &
      & + MAX(PICEPROC(KIDIA:KFDIA,JK,JPICE_AGG),0._JPRB) &
      & + MAX(PICEPROC(KIDIA:KFDIA,JK,JPICE_MELT),0._JPRB)
    ZMELTFRAC(KIDIA:KFDIA) = MIN(1._JPRB,MAX(0._JPRB, &
      & PICEPROC(KIDIA:KFDIA,JK,JPICE_MELT)/MAX(ZICEBEFORE(KIDIA:KFDIA),ZEPSEC)))
    ZMELTNUM(KIDIA:KFDIA) = ZMELTFRAC(KIDIA:KFDIA)*ZICNC(KIDIA:KFDIA,JK)
    ZICNC(KIDIA:KFDIA,JK) = ZICNC(KIDIA:KFDIA,JK)-ZMELTNUM(KIDIA:KFDIA)
    ZCDNCACT(KIDIA:KFDIA,JK) = ZCDNCACT(KIDIA:KFDIA,JK)+ZMELTNUM(KIDIA:KFDIA)
  END DO

  ! Apply the OIFS implicit ice fall operator to number mixing ratio.
  ZNUMFLUX(KIDIA:KFDIA) = 0._JPRB
  DO JK=1,KLEV
    ZDPG(KIDIA:KFDIA) = (PRS1(KIDIA:KFDIA,JK)-PRS1(KIDIA:KFDIA,JK-1))/RG
    ZNUMMR(KIDIA:KFDIA) = ZICNC(KIDIA:KFDIA,JK)/ZRHO(KIDIA:KFDIA,JK)
    ZNUMMR(KIDIA:KFDIA) = (ZNUMMR(KIDIA:KFDIA) &
      & + ZNUMFLUX(KIDIA:KFDIA)*time_step_len/MAX(ZDPG(KIDIA:KFDIA),ZEPSEC)) &
      & / (1._JPRB+MAX(PICEPROC(KIDIA:KFDIA,JK,JPICE_FALL),0._JPRB))
    ZNUMFLUX(KIDIA:KFDIA) = MAX(PICEPROC(KIDIA:KFDIA,JK,JPICE_FALL),0._JPRB) &
      & * ZNUMMR(KIDIA:KFDIA)*ZDPG(KIDIA:KFDIA)/time_step_len
    ZICNC(KIDIA:KFDIA,JK) = ZNUMMR(KIDIA:KFDIA)*ZRHO(KIDIA:KFDIA,JK)
  END DO

  ! Remove ice number by aggregation/self-collection and droplets by riming.
  DO JK=1,KLEV
    ZICEBEFORE(KIDIA:KFDIA) = MAX(PIP(KIDIA:KFDIA,JK),0._JPRB) &
      & + MAX(PICEPROC(KIDIA:KFDIA,JK,JPICE_AGG),0._JPRB)
    ZAGGFRAC(KIDIA:KFDIA) = MIN(1._JPRB,MAX(0._JPRB, &
      & PICEPROC(KIDIA:KFDIA,JK,JPICE_AGG)/MAX(ZICEBEFORE(KIDIA:KFDIA),ZEPSEC)))
    ZSELFLOSS(KIDIA:KFDIA) = 0.5_JPRB*time_step_len*(17.5_JPRB/500._JPRB) &
      & * ZRHO(KIDIA:KFDIA,JK)*(1.3_JPRB/ZRHO(KIDIA:KFDIA,JK))**(1._JPRB/3._JPRB) &
      & * ZICNC(KIDIA:KFDIA,JK)*MAX(PIP(KIDIA:KFDIA,JK),0._JPRB) &
      & / MAX(ZAP(KIDIA:KFDIA,JK),0.01_JPRB)
    ZTOTALLOSS(KIDIA:KFDIA) = MIN(ZICNC(KIDIA:KFDIA,JK), &
      & ZAGGFRAC(KIDIA:KFDIA)*ZICNC(KIDIA:KFDIA,JK)+MAX(ZSELFLOSS(KIDIA:KFDIA),0._JPRB))
    ZICNC(KIDIA:KFDIA,JK) = ZICNC(KIDIA:KFDIA,JK)-ZTOTALLOSS(KIDIA:KFDIA)

    ZLIQBEFORE(KIDIA:KFDIA) = MAX(PLP(KIDIA:KFDIA,JK),0._JPRB) &
      & + MAX(PSNOWACL(KIDIA:KFDIA,JK),0._JPRB)
    ZRIMEFRAC(KIDIA:KFDIA) = MIN(1._JPRB,MAX(0._JPRB, &
      & PSNOWACL(KIDIA:KFDIA,JK)/MAX(ZLIQBEFORE(KIDIA:KFDIA),ZEPSEC)))
    ZCDNCACT(KIDIA:KFDIA,JK) = (1._JPRB-ZRIMEFRAC(KIDIA:KFDIA)) &
      & * ZCDNCACT(KIDIA:KFDIA,JK)
  END DO

  ! Add one ice crystal for each splinter mass transferred by CLOUDSC.
  ZNISEC(KIDIA:KFDIA,:) = ZRHO(KIDIA:KFDIA,:) &
    & * MAX(PICEPROC(KIDIA:KFDIA,:,JPICE_SEC),0._JPRB)/ZSEC_ICE_MASS
  ZICNC(KIDIA:KFDIA,:) = ZICNC(KIDIA:KFDIA,:) + ZNISEC(KIDIA:KFDIA,:)

  LL1(KIDIA:KFDIA,:) = LL_CC(KIDIA:KFDIA,:) .AND. (PIP(KIDIA:KFDIA,:) > 1.E-12_JPRB)
  ZTMP1_2D(KIDIA:KFDIA,:) = MAX(ZICNC(KIDIA:KFDIA,:),ZMIN_ICNC)
  ZICNC(KIDIA:KFDIA,:) = MERGE(ZTMP1_2D(KIDIA:KFDIA,:),1.E-12_JPRB,LL1(KIDIA:KFDIA,:))

  CALL HAM_IN_SETUP(KFDIA,KLON,KLEV,ZKROW, ZRHO,ZXTM1,ZXTTE,ZCDNCACT, &
                    ZRWETKI,ZRWETAI,ZRWETCI, ZFRACDUSOL,ZFRACDUAI,ZFRACDUCI, &
                    ZFRACBCSOL,ZFRACBCINSOL,ZASCS,ZAPNX,ZAPRX,ZAPSIGX,LD_HET, &
                    ZM6RP,ZNACT_STRAT,ZNACT_CONV)

  DO JK=1,KLEV
    ZESI(KIDIA:KFDIA,JK) = EXP(9.550426_JPRB - 5723.265_JPRB / PTP0(KIDIA:KFDIA,JK) &
      & + 3.53068_JPRB * LOG(PTP0(KIDIA:KFDIA,JK)) &
      & - 0.00728332_JPRB * PTP0(KIDIA:KFDIA,JK)) * 0.622_JPRB / PRSF1(KIDIA:KFDIA,JK)
  END DO

  PRV_ICE(KIDIA:KFDIA,:) = MAX(PGFL_YRE_ICE(KIDIA:KFDIA,:),1.E-6_JPRB) * 0.9_JPRB
  SICE(KIDIA:KFDIA,:) = PQP0(KIDIA:KFDIA,:) / ZESI(KIDIA:KFDIA,:) - 1._JPRB
  SELECT CASE (KNIC_CIRRUS)
  CASE (1)
    LL_ICE(KIDIA:KFDIA,:) = (SICE(KIDIA:KFDIA,:) > 0._JPRB) .AND. &
                            (PTP(KIDIA:KFDIA,:) < 235.15_JPRB)
    ZTMP2_2D(KIDIA:KFDIA,:) = 0.75_JPRB * ZRHO(KIDIA:KFDIA,:) * SICE(KIDIA:KFDIA,:) * ZESI(KIDIA:KFDIA,:) &
        & / (RPI*RHOICE*PRV_ICE(KIDIA:KFDIA,:)**3) - ZICNC(KIDIA:KFDIA,:)
    ZTMP3_2D(KIDIA:KFDIA,:) = ZRHO(KIDIA:KFDIA,:)*ZASCS(KIDIA:KFDIA,:) &
        & - ZICNC(KIDIA:KFDIA,:)
    ZTMP1_2D(KIDIA:KFDIA,:) = MAX(MIN(ZTMP2_2D(KIDIA:KFDIA,:),ZTMP3_2D(KIDIA:KFDIA,:)),0._JPRB)
    ZNINUCL(KIDIA:KFDIA,:) = MERGE(ZTMP1_2D(KIDIA:KFDIA,:),0._JPRB,LL_ICE(KIDIA:KFDIA,:))
  CASE (2)
    ZVERVX(KIDIA:KFDIA,:) = PCIRRUS_W(KIDIA:KFDIA,:)
    ZAPNX_AVAILABLE(KIDIA:KFDIA,:,:) = 1.E-6_JPRB*MAX(ZAPNX(KIDIA:KFDIA,:,:),0._JPRB)
    ZAPNX_AVAILABLE(KIDIA:KFDIA,:,1) = MAX(1.E-6_JPRB, &
      & 1.E-6_JPRB*MAX(ZAPNX(KIDIA:KFDIA,:,1)-ZICNC(KIDIA:KFDIA,:),0._JPRB))
    ZRI(KIDIA:KFDIA,:) = 0._JPRB
    ZNICEX(KIDIA:KFDIA,:) = 0._JPRB
    DO JK=KTDIA,KLEV
      CALL XFRZMSTR(LD_HET,.TRUE.,time_step_len,KLEV,KLON,KFDIA,JK,NFRZMOD, &
        & SICE(:,JK),ZVERVX(:,JK),ZAPNX_AVAILABLE(:,JK,:),ZAPRX(:,JK,:), &
        & ZAPSIGX(:,JK,:),PTP0,273.15_JPRB,ZEPSEC,PRSF1,235.15_JPRB,ZRI,ZNICEX)
    END DO
    ZTMP2_2D(KIDIA:KFDIA,:) = 0.75_JPRB*ZRHO(KIDIA:KFDIA,:) &
      & * MAX(SICE(KIDIA:KFDIA,:),0._JPRB)*ZESI(KIDIA:KFDIA,:) &
      & / (RPI*RHOICE*MAX(ZRI(KIDIA:KFDIA,:),1.E-6_JPRB)**3) &
      & - ZICNC(KIDIA:KFDIA,:)
    ZTMP3_2D(KIDIA:KFDIA,:) = ZRHO(KIDIA:KFDIA,:)*ZASCS(KIDIA:KFDIA,:) &
      & - ZICNC(KIDIA:KFDIA,:)
    ZNINUCL(KIDIA:KFDIA,:) = MIN(MAX(ZNICEX(KIDIA:KFDIA,:),0._JPRB), &
      & MAX(ZTMP2_2D(KIDIA:KFDIA,:),0._JPRB),MAX(ZTMP3_2D(KIDIA:KFDIA,:),0._JPRB))
  CASE DEFAULT
    ZNINUCL(KIDIA:KFDIA,:) = 0._JPRB
  END SELECT
  ZICNC(KIDIA:KFDIA,:) = ZICNC(KIDIA:KFDIA,:) + ZNINUCL(KIDIA:KFDIA,:)

  ZRHO_RCP(KIDIA:KFDIA,:) = 1._JPRB / ZRHO(KIDIA:KFDIA,:)
  TEMPLWC(KIDIA:KFDIA,:) = TEMPLWC(KIDIA:KFDIA,:) / ZRHO(KIDIA:KFDIA,:)
  LL4_2D(KIDIA:KFDIA,:) = (PAP(KIDIA:KFDIA,:) >= ZEPSEC) .AND. &
                          (PTP(KIDIA:KFDIA,:) > 235.15_JPRB)
  ZTMP1_2D(KIDIA:KFDIA,:) = MAX(ZCDNCACT(KIDIA:KFDIA,:),ZCDNC_MIN(KIDIA:KFDIA,:))
  ZCDNCACT(KIDIA:KFDIA,:) = MERGE(ZTMP1_2D(KIDIA:KFDIA,:),ZCDNCACT(KIDIA:KFDIA,:),LL4_2D(KIDIA:KFDIA,:))
  LL4_2D(KIDIA:KFDIA,:) = (PAP(KIDIA:KFDIA,:) >= ZEPSEC) .AND. &
                          (PTP(KIDIA:KFDIA,:) < 273.16_JPRB)
  ZTMP1_2D(KIDIA:KFDIA,:) = MAX(ZICNC(KIDIA:KFDIA,:),ZMIN_ICNC)
  ZICNC(KIDIA:KFDIA,:) = MERGE(ZTMP1_2D(KIDIA:KFDIA,:),ZICNC(KIDIA:KFDIA,:),LL4_2D(KIDIA:KFDIA,:))
  ZCDNCACT(KIDIA:KFDIA,:) = MAX(ZCDNCACT(KIDIA:KFDIA,:),1.E-12_JPRB)
  ZICNC(KIDIA:KFDIA,:) = MAX(ZICNC(KIDIA:KFDIA,:),1.E-12_JPRB)
  ZQFRE(KIDIA:KFDIA,:) = 0._JPRB
  ZFREZ(KIDIA:KFDIA,:) = 0._JPRB
  ZFRLN(KIDIA:KFDIA,:) = 0._JPRB

  ! Apply homogeneous and mixed-phase droplet freezing.
  DO JK=1,KLEV
    LL_FRZ_BELOW_238K(KIDIA:KFDIA) = PTP(KIDIA:KFDIA,JK) <= 235.15_JPRB
    IF (ANY(LL_FRZ_BELOW_238K(KIDIA:KFDIA))) THEN
      CALL FREEZING_BELOW_238K(KLON,KFDIA,LL_FRZ_BELOW_238K(KIDIA:KFDIA), &
        & PAP(KIDIA:KFDIA,JK),ZCDNC_MIN(KIDIA:KFDIA,JK), &
        & ZICNC(KIDIA:KFDIA,JK),ZQFRE(KIDIA:KFDIA,JK),ZCDNCACT(KIDIA:KFDIA,JK), &
        & ZFREZ(KIDIA:KFDIA,JK),TEMPIWC(KIDIA:KFDIA,JK),TEMPLWC(KIDIA:KFDIA,JK))
    END IF

    LL_MXPHASE_FRZ(KIDIA:KFDIA) = (PIP(KIDIA:KFDIA,JK) / MAX(ZAP(KIDIA:KFDIA,JK),ZEPSEC) > ZEPSEC) .AND. &
      & (PTP(KIDIA:KFDIA,JK) < 273.16_JPRB) .AND. (PTP(KIDIA:KFDIA,JK) > 235.15_JPRB) .AND. &
      & (ZCDNCACT(KIDIA:KFDIA,JK) >= ZCDNC_MIN(KIDIA:KFDIA,JK)) .AND. LL_CC(KIDIA:KFDIA,JK)
    IF (ANY(LL_MXPHASE_FRZ(KIDIA:KFDIA))) THEN
      CALL HET_MXPHASE_FREEZING(KLON,KFDIA,LL_MXPHASE_FRZ,PRSF1(KIDIA:KFDIA,JK), &
        & ZTKEM1(KIDIA:KFDIA,JK),PVERVEL(KIDIA:KFDIA,JK),PAP(KIDIA:KFDIA,JK), &
        & ZFRACBCSOL(KIDIA:KFDIA,JK),ZFRACBCINSOL(KIDIA:KFDIA,JK), &
        & ZFRACDUSOL(KIDIA:KFDIA,JK),ZFRACDUAI(KIDIA:KFDIA,JK),ZFRACDUCI(KIDIA:KFDIA,JK), &
        & ZRHO(KIDIA:KFDIA,JK),ZRHO_RCP(KIDIA:KFDIA,JK), &
        & ZRWETKI(KIDIA:KFDIA,JK),ZRWETAI(KIDIA:KFDIA,JK),ZRWETCI(KIDIA:KFDIA,JK), &
        & PTP(KIDIA:KFDIA,JK),ZCDNC_MIN(KIDIA:KFDIA,JK), &
        & ZICNC(KIDIA:KFDIA,JK),ZCDNCACT(KIDIA:KFDIA,JK),ZFREZ(KIDIA:KFDIA,JK), &
        & TEMPIWC(KIDIA:KFDIA,JK),TEMPLWC(KIDIA:KFDIA,JK),ZFRLN(KIDIA:KFDIA,JK))
    END IF
  END DO

  ZICNC(KIDIA:KFDIA,:) = MIN(ZICNC(KIDIA:KFDIA,:),1.E7_JPRB)
  ZICNC(KIDIA:KFDIA,:) = MERGE(ZICNC(KIDIA:KFDIA,:),ZMIN_ICNC,LICECLD(KIDIA:KFDIA,:))
ELSE
  ZICNC(KIDIA:KFDIA,:) = MERGE(ZICNC(KIDIA:KFDIA,:),PRNICE,LICECLD(KIDIA:KFDIA,:))
END IF

IF (LHOOK) CALL DR_HOOK('ICE_INTERFACE',1,ZHOOK_HANDLE)

END SUBROUTINE ICE_INTERFACE
